    private void calcularTotales() {
        double descuento = 0.0;
        try {
            if (!txtDescuento.getText().trim().isEmpty()) {
                descuento = Double.parseDouble(txtDescuento.getText().trim());
            }
        } catch (NumberFormatException e) {
            descuento = 0.0;
        }

        double impuesto = subtotalAcumulado * 0.15; // 15% ISV estándar
        double total = (subtotalAcumulado - descuento) + impuesto;
        if (total < 0) total = 0;

        lblSubTotal.setText(String.format(" Lps. %.2f", subtotalAcumulado));
        lblDescuento.setText(String.format(" Lps. %.2f", descuento));
        lblImpuestoMonto.setText(String.format(" Lps. %.2f", impuesto));
        lblTotal.setText(String.format(" Lps. %.2f", total));
    }

