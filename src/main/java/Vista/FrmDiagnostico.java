    private void btnAgregarLineaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarLineaActionPerformed
        if (cboTipo.getSelectedIndex() <= 0 || cboItem.getSelectedIndex() <= 0 || txtCantidad.getText().trim().isEmpty() || txtPrecio.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete los campos del presupuesto (Tipo, Ítem, Cantidad y Precio).", "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double cantidad = Double.parseDouble(txtCantidad.getText().trim());
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            double subtotal = cantidad * precio;

            subtotalAcumulado += subtotal;

            modeloActividades.addRow(new Object[]{
                cboTipo.getSelectedItem().toString(),
                cboItem.getSelectedItem().toString(),
                cantidad,
                String.format("%.2f", precio),
                String.format("%.2f", subtotal)
            });

            calcularTotales();
            txtCantidad.setText("");
            txtPrecio.setText("");
            JOptionPane.showMessageDialog(this, "Línea de presupuesto agregada.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cantidad y el precio deben ser valores numéricos válidos.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarLineaActionPerformed

