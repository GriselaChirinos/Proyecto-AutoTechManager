    private void btnPagarSaldoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagarSaldoActionPerformed
        // TODO add your handling code here:
                OrdenTrabajo o = UIUtil.seleccionado(cboOrden, OrdenTrabajo.class);
        if (o == null) return;
        try {
            BigDecimal saldo = pagoService.resumen(o.getId())[2];
            if (saldo.signum() == 0) { UIUtil.info(this, "La orden no tiene saldo pendiente."); return; }
            pagar(saldo);
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
        
    }//GEN-LAST:event_btnPagarSaldoActionPerformed

