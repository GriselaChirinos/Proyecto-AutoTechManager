    private void cargarOrdenes() {
        cargando = true;
        try {
            List<OrdenTrabajo> lista = new ArrayList<>();
            for (OrdenTrabajo o : ordenService.listar())
                if (o.getEstado() != EstadoOrden.CANCELADA && o.getEstado() != EstadoOrden.RECHAZADA
                        && o.getEstado() != EstadoOrden.RECIBIDA && o.getEstado() != EstadoOrden.EN_DIAGNOSTICO) lista.add(o);
            UIUtil.llenarCombo(cboOrden, lista);
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        } finally {
            cargando = false;
        }
        mostrarResumen();
    }
 
    private void mostrarResumen() {
        OrdenTrabajo o = UIUtil.seleccionado(cboOrden, OrdenTrabajo.class);
        if (o == null) { txtTotal.setText("-"); txtPagado.setText("-"); txtSaldo.setText("-"); txtEstado.setText("-"); return; }
        try {
            BigDecimal[] r = pagoService.resumen(o.getId());
            txtTotal.setText("L " + r[0]);
            txtPagado.setText("L " + r[1]);
            txtSaldo.setText("L " + r[2]);
            txtEstado.setText(o.getEstado().toString());
            UIUtil.llenar(tblPagos, pagoService.pagosDeOrden(o.getId()));
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
    }
 
    private void pagar(BigDecimal monto) {
        OrdenTrabajo o = UIUtil.seleccionado(cboOrden, OrdenTrabajo.class);
        if (o == null) { UIUtil.info(this, "Seleccione una orden."); return; }
        try {  
            BigDecimal[] r = pagoService.resumen(o.getId());

System.out.println("ID Orden: " + o.getId());
System.out.println("Total: " + r[0]);
System.out.println("Pagado: " + r[1]);
System.out.println("Saldo: " + r[2]);
System.out.println("Monto a pagar: " + monto);

            
            pagoService.registrar(o.getId(), monto, (String) cboMetodo.getSelectedItem(), UIUtil.texto(txtReferencia));
            UIUtil.info(this, "Pago registrado.");
            txtMonto.setText("");
            mostrarResumen();
        } catch (AutoTechException e) {
            UIUtil.error(this, e);          // por ejemplo: el pago excede el saldo pendiente
        }
    }
 
