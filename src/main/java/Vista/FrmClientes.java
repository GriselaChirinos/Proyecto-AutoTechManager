    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtIdentidad.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() || txtApellido.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, complete al menos la Identidad, Nombre y Apellido.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    String sql = "INSERT INTO dbo.Clientes (Identidad, Nombre, Apellido, Telefono, Correo, Direccion, Activo, FechaRegistro) VALUES (?, ?, ?, ?, ?, ?, ?, GETDATE())";

    try (java.sql.Connection conn = config.Conexion.obtener();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

        pstmt.setString(1, txtIdentidad.getText().trim());
        pstmt.setString(2, txtNombre.getText().trim());
        pstmt.setString(3, txtApellido.getText().trim());
        pstmt.setString(4, txtTelefono.getText().trim());
        pstmt.setString(5, txtCorreo.getText().trim());
        pstmt.setString(6, txtDireccion.getText().trim());
        pstmt.setBoolean(7, chkActivo.isSelected());

        pstmt.executeUpdate();
        
        JOptionPane.showMessageDialog(this, "¡Cliente guardado en la base de datos exitosamente!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        
        cargarClientesDesdeBD();
        limpiarCamposFormulario();
        bloquearCampos(false);

    } catch (java.sql.SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + ex.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

