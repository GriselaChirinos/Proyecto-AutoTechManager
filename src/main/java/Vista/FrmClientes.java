    private void cargarClientesDesdeBD() {
    modeloTabla.setRowCount(0);
    String sql = "SELECT IdCliente, Identidad, Nombre, Apellido, Telefono, Correo, Activo FROM dbo.Clientes";

    try (java.sql.Connection conn = config.Conexion.obtener();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery(sql)) {

        while (rs.next()) {
            modeloTabla.addRow(new Object[]{
                rs.getInt("IdCliente"),
                rs.getString("Identidad"),
                rs.getString("Nombre"),
                rs.getString("Apellido"),
                rs.getString("Telefono"),
                rs.getString("Correo"),
                rs.getBoolean("Activo")
            });
        }
    } catch (java.sql.SQLException ex) {
        logger.log(java.util.logging.Level.SEVERE, null, ex);
    }
}

