    private void cargarTabla() {
        try {
            servicios = catalogo.listar();
            List<Object[]> filas = new ArrayList<>();
            for (Servicio s : servicios)            // getCategoria() y getDiasGarantia() son polimórficos
                filas.add(new Object[]{s.getId(), s.getCodigo(), s.getNombre(),
                                       s.getCategoria() + " (garantía " + s.getDiasGarantia() + " d)",
                                       s.getNivel(), s.getCostoManoObra(), s.getTiempoEstimadoHoras()});
            UIUtil.llenar(tblServicios, new String[]{"IdServicio", "Código", "Nombre", "Categoría", "Nivel", "Mano de obra", "Horas"}, filas);
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
    }
 
    private void cargarRepuestosAsociados() {
        List<Object[]> filas = new ArrayList<>();
        try {
            if (actual != null) filas = catalogo.repuestosDelServicio(actual.getId());
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
        UIUtil.llenar(tblRepuestosServicio, new String[]{"IdRepuesto", "Código", "Repuesto", "Cantidad", "Precio"}, filas);
    }
 
    private void nuevo() {
        actual = null;
        txtCodigo.setText(""); txtNombre.setText(""); txaDescripcion.setText("");
        txtCosto.setText(""); txtHoras.setText("");
        cboNivel.setSelectedIndex(0);
        cargarRepuestosAsociados();

    }

