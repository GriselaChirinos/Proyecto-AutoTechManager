    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        // TODO add your handling code here:
        int fila = tblRepuestosServicio.getSelectedRow();
        if (actual == null || fila < 0) { UIUtil.info(this, "Seleccione un repuesto asociado."); return; }
        try {
            int idRepuesto = (Integer) tblRepuestosServicio.getValueAt(fila, 0);
            catalogo.quitarRepuesto(actual.getId(), idRepuesto);
            cargarRepuestosAsociados();
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
    }//GEN-LAST:event_btnQuitarActionPerformed

