    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here
        try {
            Servicio s = ServicioFactory.crear(cboNivel.getSelectedIndex() + 1);   // subclase según el nivel
            s.setId(actual == null ? 0 : actual.getId());
            s.setCodigo(UIUtil.texto(txtCodigo));
            s.setNombre(UIUtil.texto(txtNombre));
            s.setDescripcion(txaDescripcion.getText().trim());
            s.setCostoManoObra(Validador.decimal(txtCosto.getText(), "Mano de obra"));
            s.setTiempoEstimadoHoras(Validador.decimalPositivo(txtHoras.getText(), "Horas").doubleValue());
            catalogo.guardar(s);
            UIUtil.info(this, "Servicio guardado. Las órdenes ya registradas conservan su precio original.");
            cargarTabla();
            nuevo();
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

        private void tblServiciosMouseClicked(java.awt.event.MouseEvent evt) {
        int fila = tblServicios.getSelectedRow();
        if (fila < 0) return;
        actual = servicios.get(fila);
        txtCodigo.setText(actual.getCodigo());
        txtNombre.setText(actual.getNombre());
        txaDescripcion.setText(actual.getDescripcion());
        cboNivel.setSelectedIndex(actual.getNivel() - 1);
        txtCosto.setText(actual.getCostoManoObra().toPlainString());
        txtHoras.setText(String.valueOf(actual.getTiempoEstimadoHoras()));
        cargarRepuestosAsociados();
    }

