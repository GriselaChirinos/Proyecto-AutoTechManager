    private void cargarStockCritico() {
        try {
            List<Object[]> filas = new ArrayList<>();
            for (Repuesto r : new InventarioService().listarCriticos())
                filas.add(new Object[]{r.getCodigo(), r.getNombre(), r.getStock(), r.getStockMinimo()});
            UIUtil.llenar(tblStockCritico, new String[]{"Código", "Repuesto", "Stock", "Mínimo"}, filas);
        } catch (AutoTechException e) {
            UIUtil.error(this, e);
        }
    }


