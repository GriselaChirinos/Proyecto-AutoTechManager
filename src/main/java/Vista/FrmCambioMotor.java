    private void cargarOrdenes() {
        cboDestino2.removeAllItems();
        cboDestino2.addItem("-- Seleccione una Orden --");
        String sql = "SELECT IdOrden FROM dbo.OrdenesTrabajo";
        try (Connection conn = config.Conexion.obtener();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {
            while (rs.next()) {
                cboDestino2.addItem(rs.getInt("IdOrden") + "");
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
        }
    }

    private void cargarDestinos() {
        cboDestino1.removeAllItems();
        cboDestino1.addItem("Almacén / Stock");
        cboDestino1.addItem("Chatarra / Desecho");
        cboDestino1.addItem("Garantía Proveedor");
    }

    private void cargarMotoresNuevos() {
        cboMotorNuevo.removeAllItems();
        cboMotorNuevo.addItem("-- Seleccione Motor --");
        String sql = "SELECT IdMotor, SerieMotor, Modelo FROM dbo.Motores";
        try (Connection conn = config.Conexion.obtener();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {
            while (rs.next()) {
                cboMotorNuevo.addItem(rs.getInt("IdMotor") + " - " + rs.getString("SerieMotor") + " (" + rs.getString("Modelo") + ")");
            }
        } catch (SQLException ex) {
            cboMotorNuevo.addItem("1 - MOT-998822 (Estándar)");
            cboMotorNuevo.addItem("2 - MOT-774411 (Potenciado)");
        }
    }

    private void cargarSustitucionesDesdeBD() {
        if (modeloTabla == null) return;
        modeloTabla.setRowCount(0);
        String sql = "SELECT IdOrden, SerieAnterior, SerieNueva, DestinoRetirado, ValidacionPruebas, FechaInstalacion FROM dbo.SustitucionMotor";
        try (Connection conn = config.Conexion.obtener();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {
            while (rs.next()) {
                modeloTabla.addRow(new Object[]{
                    rs.getInt("IdOrden"),
                    rs.getString("SerieAnterior"),
                    rs.getString("SerieNueva"),
                    rs.getString("DestinoRetirado"),
                    rs.getString("ValidacionPruebas"),
                    rs.getDate("FechaInstalacion")
                });
            }
        } catch (SQLException ex) {
            // Si la tabla física no existe aún, se gestiona en memoria sin interrumpir
        }
    }

