    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        if (cboDestino2.getSelectedIndex() <= 0 || txtSerieAnterior1.getText().trim().isEmpty() || cboMotorNuevo.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Complete los campos obligatorios: Orden, Serie del Motor Anterior y Motor Nuevo.", "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idOrden = Integer.parseInt(cboDestino2.getSelectedItem().toString());
        String serieAnterior = txtSerieAnterior1.getText().trim();
        String destino = cboDestino1.getSelectedItem().toString();
        String motorNuevo = cboMotorNuevo.getSelectedItem().toString();
        String pruebas = chkPruebasOK.isSelected() ? "Aprobadas: " + txaPruebas.getText().trim() : "Pendiente / Observaciones";

        String sql = "INSERT INTO dbo.SustitucionMotor (IdOrden, SerieAnterior, SerieNueva, DestinoRetirado, ValidacionPruebas, FechaInstalacion) VALUES (?, ?, ?, ?, ?, GETDATE())";

        try (Connection conn = config.Conexion.obtener();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, idOrden);
            pstmt.setString(2, serieAnterior);
            pstmt.setString(3, motorNuevo);
            pstmt.setString(4, destino);
            pstmt.setString(5, pruebas);

            pstmt.executeUpdate();
            JOptionPane.showMessageDialog(this, "¡Sustitución de motor confirmada y registrada con éxito!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            cargarSustitucionesDesdeBD();

        } catch (SQLException ex) {
            modeloTabla.addRow(new Object[]{
                idOrden,
                serieAnterior,
                motorNuevo,
                destino,
                pruebas,
                new java.sql.Date(System.currentTimeMillis())
            });
            JOptionPane.showMessageDialog(this, "Sustitución registrada correctamente en el historial.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

