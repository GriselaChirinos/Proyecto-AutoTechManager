    private void cboDestino2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboDestino2ActionPerformed
        if (cboDestino2.getSelectedIndex() > 0) {
            String idOrden = cboDestino2.getSelectedItem().toString();
            String sql = "SELECT v.Marca + ' ' + v.Modelo + ' (' + v.Placa + ')' AS Auto FROM dbo.OrdenesTrabajo o INNER JOIN dbo.Vehiculos v ON o.IdVehiculo = v.IdVehiculo WHERE o.IdOrden = ?";
            try (Connection conn = config.Conexion.obtener();
                 PreparedStatement pstmt = conn.prepareStatement(sql)) {
                pstmt.setInt(1, Integer.parseInt(idOrden));
                try (ResultSet rs = pstmt.executeQuery()) {
                    if (rs.next()) {
                        lblVehiculo.setText(" " + rs.getString("Auto"));
                    }
                }
            } catch (SQLException ex) {
                lblVehiculo.setText(" Vehículo asociado");
            }
        } else {
            lblVehiculo.setText("");
        }
    }//GEN-LAST:event_cboDestino2ActionPerformed

